"""Native, single-user overview built from measured local statistics."""
import datetime as dt
import tkinter as tk
from tkinter import ttk

BACKGROUND = '#0E1415'
SURFACE = '#1B2122'
TEXT = '#DEE3E5'
MUTED = '#A2B4B8'
ACCENT = '#82D3E5'


def number(value):
    return f'{value:,}' if type(value) is int and value >= 0 else 'Not measured'


class Dashboard(ttk.Frame):
    def __init__(self, parent):
        super().__init__(parent, padding=20)
        ttk.Label(self, text='Your local AI, at a glance', style='Title.TLabel').pack(anchor='w')
        self.subtitle = tk.StringVar(value='Connect your phone and start a conversation to see measured activity.')
        ttk.Label(self, textvariable=self.subtitle, style='Muted.TLabel').pack(anchor='w', pady=(4, 18))
        tiles = ttk.Frame(self)
        tiles.pack(fill='x')
        self.metrics = {}
        for column, (key, label) in enumerate([('total', 'TOTAL TOKENS GENERATED'), ('today', 'GENERATED TODAY'), ('speed', 'GENERATION SPEED')]):
            tile = ttk.Frame(tiles, padding=16, style='Card.TFrame')
            tile.grid(row=0, column=column, sticky='nsew', padx=(0, 10 if column < 2 else 0))
            tiles.columnconfigure(column, weight=1, uniform='metric')
            ttk.Label(tile, text=label, style='CardMuted.TLabel').pack(anchor='w')
            self.metrics[key] = tk.StringVar(value='Not measured')
            ttk.Label(tile, textvariable=self.metrics[key], style='Metric.TLabel').pack(anchor='w', pady=(8, 0))
        heading = ttk.Frame(self)
        heading.pack(fill='x', pady=(22, 8))
        ttk.Label(heading, text='Tokens generated', style='Section.TLabel').pack(side='left')
        ttk.Label(heading, text='Last 7 days · local time', style='Muted.TLabel').pack(side='right')
        self.chart = tk.Canvas(self, height=220, bg=SURFACE, highlightthickness=0)
        self.chart.pack(fill='x')
        self.chart.bind('<Configure>', lambda _: self.draw())
        self.days = []
        self.coverage = tk.StringVar(value='Output includes reasoning when counted by your model. No token estimates.')
        ttk.Label(self, textvariable=self.coverage, style='Muted.TLabel').pack(anchor='w', pady=(8, 16))
        ttk.Label(self, text='Recent activity', style='Section.TLabel').pack(anchor='w', pady=(0, 8))
        self.jobs = ttk.Treeview(self, columns=('kind', 'model', 'status', 'time'), show='headings', height=5, selectmode='browse')
        for key, label, width in [('kind', 'WORK', 130), ('model', 'MODEL', 240), ('status', 'STATE', 210), ('time', 'UPDATED', 100)]:
            self.jobs.heading(key, text=label)
            self.jobs.column(key, width=width, minwidth=80)
        self.jobs.pack(fill='both', expand=True)
        self.link = tk.StringVar(value='Waiting for Gateway status')
        ttk.Label(self, textvariable=self.link, style='Muted.TLabel').pack(anchor='w', pady=(12, 0))

    def update_data(self, data, stale=False):
        usage = data.get('usage', {})
        self.metrics['total'].set(number(usage.get('outputTokens')))
        self.days = usage.get('days', [])
        self.metrics['today'].set(number(self.days[-1].get('outputTokens')) if self.days else 'Not measured')
        speed = usage.get('tokensPerSecond')
        self.metrics['speed'].set(f'{speed:.1f} tok/s' if isinstance(speed, (int, float)) else 'Not measured')
        self.subtitle.set('Saved measurements · waiting for a fresh connection' if stale else 'A personal view of the work generated by this Gateway.')
        missing = usage.get('unmeasuredRounds', 0)
        self.coverage.set(('Measured output only · ' + str(missing) + ' rounds have unavailable counts. ' if missing else '') + 'Includes model-counted reasoning. Totals persist across restarts.')
        for item in self.jobs.get_children():
            self.jobs.delete(item)
        for job in data.get('recentJobs', []):
            stamp = job.get('updatedAt')
            when = dt.datetime.fromtimestamp(stamp).strftime('%H:%M:%S') if isinstance(stamp, (int, float)) else 'Unavailable'
            self.jobs.insert('', 'end', values=(str(job.get('kind') or 'chat').replace('_', ' ').title(),
                job.get('model') or 'Unavailable', str(job.get('status') or 'unknown').replace('_', ' ').capitalize(), when))
        checks = data.get('checks', {})
        active = data.get('service', {}).get('activeWorkers')
        self.link.set(f"Model backend: {checks.get('backend', 'not checked')}  ·  Saved jobs: {checks.get('journal', 'not checked')}  ·  Active work: {active if active is not None else 'not measured'}")
        self.draw()

    def draw(self):
        c = self.chart
        c.delete('all')
        width, height = max(c.winfo_width(), 300), 220
        if not self.days:
            c.create_text(width / 2, height / 2, text='Your token history will appear here', fill=MUTED, font=('Segoe UI', 12))
            return
        left, right, top, bottom = 68, width - 28, 20, height - 40
        values = [day.get('outputTokens') for day in self.days]
        maximum = max([value for value in values if isinstance(value, int)] + [1])
        for fraction in (0, .5, 1):
            y = bottom - (bottom - top) * fraction
            c.create_line(left, y, right, y, fill='#303C3F')
            c.create_text(left - 12, y, text=f'{round(maximum * fraction):,}', anchor='e', fill=MUTED, font=('Segoe UI', 9))
        step = (right - left) / max(len(values) - 1, 1)
        points = []
        for index, (day, value) in enumerate(zip(self.days, values)):
            x = left + index * step
            c.create_text(x, bottom + 23, text=day['day'][5:], fill=MUTED, font=('Segoe UI', 9))
            if value is None:
                c.create_text(x, bottom - 16, text='N/A', fill=MUTED, font=('Segoe UI', 9))
                points = []
                continue
            y = bottom - (bottom - top) * value / maximum
            if points:
                c.create_polygon(points[-2], bottom, points[-2], points[-1], x, y, x, bottom, fill='#25434A', outline='')
                c.create_line(points[-2], points[-1], x, y, fill=ACCENT, width=3)
            c.create_oval(x - 4, y - 4, x + 4, y + 4, fill=ACCENT, outline=SURFACE, width=2)
            if value:
                c.create_text(x, max(9, y - 14), text=f'{value:,}', fill=TEXT, font=('Segoe UI', 9))
            points.extend((x, y))
