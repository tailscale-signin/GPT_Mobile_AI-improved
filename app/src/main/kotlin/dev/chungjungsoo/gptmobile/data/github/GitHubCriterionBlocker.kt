package dev.chungjungsoo.gptmobile.data.github

/** Fixed diagnostic vocabulary; private error prose is retained only in the protected ledger. */
internal enum class GitHubCriterionBlocker(val nextAction: String) {
    OUT_OF_SCOPE("KEEP_OPERATION_OUT_OF_SCOPE"),
    REPOSITORY_SCOPE_EXCLUDED("KEEP_ACCOUNT_DISCOVERY_OUT_OF_REPOSITORY_SCOPE"),
    OPERATION_IDENTITY_REQUIRED("RESOLVE_CANONICAL_OPERATION_FROM_AUTHORIZED_SCHEMA"),
    AUTHORIZATION_REQUIRED("REAUTHORIZE_EXACT_OPERATION_AND_RECHECK_SCOPE"),
    HISTORICAL_CONTRACT_CHANGED("REVALIDATE_RETAINED_RECEIPTS_AGAINST_CURRENT_CONTRACT"),
    APPROVAL_REQUIRED("OPEN_EXISTING_APPROVAL_CARD"),
    FIXTURE_APPROVAL_MODE_REQUIRED("SET_FIXTURE_ONLY_APPROVAL_MODE_BEFORE_CREATING_A_TEST_BRANCH"),
    LIVE_EVIDENCE_REQUIRED("RUN_AUTHORIZED_LIVE_FIXTURE"),
    CONTINUATION_REQUIRED("FOLLOW_EXACT_RETAINED_CONTINUATION"),
    PRECHECK_REJECTED("CORRECT_RECORDED_PRECHECK_BEFORE_DISPATCH"),
    OPERATION_FAILED("INSPECT_EXACT_FAILURE_AND_RECONCILE_BEFORE_RETRY"),
    USER_DECISION_REQUIRED("AWAIT_GENUINE_REQUIRED_USER_DECISION"),
    CHECK_SUBSCRIPTION_REQUIRED("OBSERVE_EXACT_RUN_AND_OPEN_CHECK_SUBSCRIPTION"),
    OWNED_FIXTURE_REQUIRED("PREPARE_AUTHORIZED_OWNED_FIXTURE_AND_CLEANUP_RESERVE"),
    ISSUE_ID_REQUIRED("READ_ISSUE_INVENTORY_AND_SELECT_OBSERVED_ISSUE"),
    PULL_REQUEST_ID_REQUIRED("READ_PULL_REQUEST_INVENTORY_AND_SELECT_OBSERVED_PR"),
    WORKFLOW_RUN_OR_JOB_REQUIRED("OBSERVE_APPLICABLE_WORKFLOW_RUN_AND_EXECUTED_JOB"),
    RELEASE_OR_TAG_REQUIRED("READ_RELEASE_OR_TAG_INVENTORY"),
    REPOSITORY_INPUT_REQUIRED("OBSERVE_EXACT_REPOSITORY_REVISION_OR_SOURCE_PATH"),
    EXECUTION_NOT_EXERCISED("RUN_NAMED_AUTHORIZED_OPERATION_WITHIN_REMAINING_BUDGET"),
    BLOCKER_DETAIL_NOT_RECORDED("INSPECT_PROTECTED_CRITERION_AND_RECORD_MISSING_PREREQUISITE");

    companion object {
        fun from(value: String): GitHubCriterionBlocker? = entries.firstOrNull { it.name == value }
    }
}
