#!/usr/bin/env python3
"""Generate both metadata allowlists from the reviewed protocol contract."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/contracts/gateway-diagnostic-schema-v2.json'


def generated():
    # The protocol identity uses UTF-8 with LF line endings, independently of
    # Git's platform checkout conversion. Other contract bytes remain significant.
    raw = SOURCE.read_text(encoding='utf-8').encode('utf-8')
    schema = json.loads(raw)
    digest = hashlib.sha256(raw).hexdigest()
    fields = {'choices': 'ENUMS', 'numeric_attributes': 'NUMBER_ATTRIBUTES',
              'digest_attributes': 'DIGEST_ATTRIBUTES', 'boolean_attributes': 'BOOL_ATTRIBUTES',
              'enum_attributes': 'ENUM_ATTRIBUTES'}
    py = '# Generated by scripts/generate_diagnostic_schema.py; edit the JSON contract.\n'
    py += f'SCHEMA_DIGEST = {digest!r}\n'
    kt = 'package dev.chungjungsoo.gptmobile.data.network.gateway\n\n'
    kt += '// Generated by scripts/generate_diagnostic_schema.py; edit the JSON contract.\n'
    kt += 'internal object GatewayDiagnosticSchema {\n'
    kt += f'    const val DIGEST = "{digest}"\n'
    for key, name in fields.items():
        value = schema[key]
        kt_name = {'choices': 'choices', 'numeric_attributes': 'numericAttributes',
                   'digest_attributes': 'digestAttributes', 'boolean_attributes': 'boolAttributes',
                   'enum_attributes': 'enumAttributes'}[key]
        if isinstance(value, dict):
            py += name + ' = {\n'
            kt += f'    val {kt_name} = mapOf(\n'
            for index, (field, values) in enumerate(value.items()):
                py += f'    {field!r}: {set_literal(values)},\n'
                suffix = ',' if index < len(value) - 1 else ''
                kt += f'        "{field}" to setOf({", ".join(json.dumps(v) for v in values)}){suffix}\n'
            py += '}\n'
            kt += '    )\n'
        else:
            py += f'{name} = {set_literal(value)}\n'
            kt += f'    val {kt_name} = setOf({", ".join(json.dumps(v) for v in value)})\n'
    kt += '}\n'
    return {ROOT / 'gateway/v14/diagnostic_schema.py': py,
            ROOT / 'app/src/main/kotlin/dev/chungjungsoo/gptmobile/data/network/gateway/GatewayDiagnosticSchema.kt': kt}


def set_literal(values):
    return '{' + ', '.join(repr(v) for v in values) + '}' if values else 'set()'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generated().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Generated diagnostic contract is stale: {path.relative_to(ROOT)}')
        else:
            path.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
