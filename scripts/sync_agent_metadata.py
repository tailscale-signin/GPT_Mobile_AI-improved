#!/usr/bin/env python3
"""Keep agent instruction facts derived from build/database sources."""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
START, END = '<!-- BEGIN GENERATED BUILD FACTS -->', '<!-- END GENERATED BUILD FACTS -->'


def generated(root):
    gradle = (root / 'app/build.gradle.kts').read_text()
    database = (root / 'app/src/main/kotlin/dev/chungjungsoo/gptmobile/data/database/ChatDatabaseV2.kt').read_text()
    def number(pattern, text):
        values = re.findall(pattern, text)
        if len(set(values)) != 1:
            raise ValueError('Build metadata is missing or ambiguous: ' + pattern)
        return int(values[0])
    minimum = number(r'\bminSdk\s*=\s*(\d+)', gradle)
    target = number(r'\btargetSdk\s*=\s*(\d+)', gradle)
    schema = number(r'\bversion\s*=\s*(\d+)', database)
    export = root / f'app/schemas/dev.chungjungsoo.gptmobile.data.database.ChatDatabaseV2/{schema}.json'
    if not export.is_file():
        raise ValueError('Current Room schema export is missing')
    return f'{START}\nGenerated by `python3 scripts/sync_agent_metadata.py`. Edit build/schema sources first.\n\n- **Min SDK**: {minimum}\n- **Target SDK**: {target}\n- **Database**: Room (`ChatDatabaseV2`, schema v{schema}) with explicit migrations\n{END}'


def synchronize(root=ROOT, check=False):
    block = generated(root)
    drift = []
    for name in ('AGENTS.md', 'CLAUDE.md'):
        path = root / name
        original = path.read_text()
        if START in original:
            if original.count(START) != 1 or original.count(END) != 1:
                raise ValueError('Invalid generated metadata markers')
            updated = re.sub(re.escape(START) + r'.*?' + re.escape(END), lambda _: block, original, flags=re.S)
        else:
            cleaned = re.sub(r'^- \*\*(?:Min SDK|Target SDK|Database)\*\*:.*\n', '', original, flags=re.M)
            updated = cleaned.rstrip() + '\n\n## Generated build facts\n\n' + block + '\n'
        if updated != original:
            drift.append(name)
            if not check:
                path.write_text(updated)
    return drift


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = synchronize(check=args.check)
    if args.check and drift:
        print('Agent build facts drift: ' + ', '.join(drift) + '. Run python3 scripts/sync_agent_metadata.py', file=sys.stderr)
        sys.exit(1)
